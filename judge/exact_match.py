class FieldKind(str, Enum):
    NUMERIC = "numeric"
    DATE = "date"
    LABEL = "label"
    MIXED = "mixed"
    PROSE = "prose"


@dataclass(frozen=True)
class ExpectedField:
    kind: FieldKind
    raw: str
    value: Decimal | date | None = None
    # Numerics found inside a MIXED field — required even though its words aren't.
    inner_numerics: tuple[Decimal, ...] = ()


@dataclass(frozen=True)
class ComparisonPolicy:
    """How `expected_answer` is compared to the platform answer.

    Every field is a decision recorded on the run's artefacts, so a scorecard
    always states the comparison it was produced under (§11.1 provenance).
    """

    # "value"  — 28,731 == 28731 == 28731.00   (default; see module docstring)
    # "string" — byte-identical rendering required (the pre-OI-2 reading)
    numeric_form: Literal["value", "string"] = "value"
    # Require each LABEL to appear, and to sit beside its own value.
    require_labels: bool = True
    # How far a label may be from its value and still count as attached. Wide
    # enough for "Awareness led the quarter with 35,726 campaigns", narrow
    # enough that a different record's number cannot be borrowed.
    label_proximity_chars: int = 120
    # Recognise month-name date renderings on the platform side.
    prose_dates: bool = True

    @property
    def label(self) -> str:
        parts = [f"numeric={self.numeric_form}"]
        parts.append("labels=required" if self.require_labels else "labels=ignored")
        if self.require_labels:
            parts.append(f"proximity={self.label_proximity_chars}")
        if not self.prose_dates:
            parts.append("iso-dates-only")
        return " ".join(parts)

    @property
    def is_certified_default(self) -> bool:
        return self == DEFAULT_POLICY


DEFAULT_POLICY = ComparisonPolicy()
# The pre-OI-2 reading of "identical": rendering must match byte for byte.
STRICT_STRING_POLICY = ComparisonPolicy(numeric_form="string")


class ExactMatchResult(str, Enum):
    PASS = "pass"
    FAIL = "fail"
    NOT_APPLICABLE = "not_applicable"  # nothing deterministic to compare
    ERROR = "error"  # the platform never answered — infra, not accuracy
    # The platform answered, but with a question rather than an answer (§2e).
    # Not a wrong answer and not an outage: there is no value to compare, so it
    # sits outside the percentage like ERROR does — and is named in the summary
    # rather than derived, because an exclusion that quietly raises accuracy is
    # what §14.2 condition 4 warns about.
    CLARIFICATION = "clarification"


@dataclass(frozen=True)
class ExactMatchOutcome:
    """The verdict plus why — §11.2 needs a failure a client can act on."""

    result: ExactMatchResult
    detail: str = ""
    # True when the expected answer was not in the machine-generated contract
    # shape (§9.3). Worth surfacing: the pair, not the platform, is off-spec.
    off_contract: bool = False
    # Requirement keys ("value:28731", "label:Standard", "date:2026-04-01") that
    # the platform answer did and did not satisfy. The §9.5 rephrase-group check
    # compares these across variants: two phrasings of one question that satisfy
    # different requirements is precisely the phrasing-sensitivity that section
    # asks us to surface as a platform finding.
    satisfied: tuple[str, ...] = ()
    unsatisfied: tuple[str, ...] = ()

    def __bool__(self) -> bool:  # pragma: no cover — guard against `if outcome:`
        raise TypeError("check ExactMatchOutcome.result explicitly, not truthiness")


# --- expected-side parsing --------------------------------------------------


def _as_number(text: str) -> Decimal | None:
    """Parse a field that should be wholly a number. Currency prefix allowed."""
    stripped = text.strip().lstrip("$€£¥").strip()
    if not _NUMBER_RE.fullmatch(stripped):
        return None
    try:
        return Decimal(stripped.replace(",", ""))
    except InvalidOperation:
        return None


def _as_iso_date(text: str) -> date | None:
    match = _ISO_DATE_RE.fullmatch(text.strip())
    if match is None:
        return None
    try:
        return date(int(match[1]), int(match[2]), int(match[3]))
    except ValueError:
        return None


def _classify(field: str) -> ExpectedField:
    raw = field.strip()
    as_date = _as_iso_date(raw)
    if as_date is not None:
        return ExpectedField(FieldKind.DATE, raw, value=as_date)
    as_number = _as_number(raw)
    if as_number is not None:
        return ExpectedField(FieldKind.NUMERIC, raw, value=as_number)

    if any(ch.isdigit() for ch in raw):
        inner = tuple(
            Decimal(t.replace(",", "")) for t in _NUMBER_RE.findall(_strip_dates(raw))
        )
        return ExpectedField(FieldKind.MIXED, raw, inner_numerics=inner)

    words = raw.split()
    label_shaped = (
        raw
        and len(words) <= _LABEL_MAX_WORDS
        and len(raw) <= _LABEL_MAX_CHARS
        and raw[-1] not in ".?!"
    )
    return ExpectedField(FieldKind.LABEL if label_shaped else FieldKind.PROSE, raw)


def _strip_dates(text: str) -> str:
    """Blank out date spans so their digits are not re-read as numbers."""
    return _ISO_DATE_RE.sub(lambda m: " " * len(m.group(0)), text)


def parse_expected(expected_answer: str) -> list[list[ExpectedField]]:
    """Split `expected_answer` into records of classified fields."""
    records: list[list[ExpectedField]] = []
    for record in _RECORD_SEP.split((expected_answer or "").strip()):
        if not record.strip():
            continue
        records.append([_classify(f) for f in _FIELD_SEP.split(record) if f.strip()])
    return [r for r in records if r]


# --- actual-side indexing ---------------------------------------------------


@dataclass
class _ActualIndex:
    """The platform answer in one canonical coordinate space.

    Everything — numbers, dates, labels — is located in `view`, so proximity
    between a label and a value is measurable regardless of which matcher found
    it.
    """

    view: str  # lowercased, whitespace-collapsed
    tight: str  # `view` with all spaces removed
    tight_to_view: list[int]  # tight index -> view index
    numbers: list[tuple[Decimal, int]]  # (value, position in view)
    number_strings: list[tuple[str, int]]  # (raw token, position) for "string" form
    dates: list[tuple[date, int]]


def _build_index(actual: str, policy: ComparisonPolicy) -> _ActualIndex:
    view = _WS.sub(" ", (actual or "").strip().lower())

    tight_chars: list[str] = []
    tight_to_view: list[int] = []
    for i, ch in enumerate(view):
        if not ch.isspace():
            tight_chars.append(ch)
            tight_to_view.append(i)

    dates: list[tuple[date, int]] = []
    masked = view
    for match in _ISO_DATE_RE.finditer(view):
        try:
            dates.append(
                (date(int(match[1]), int(match[2]), int(match[3])), match.start())
            )
        except ValueError:
            continue
    masked = _ISO_DATE_RE.sub(lambda m: " " * len(m.group(0)), masked)

    if policy.prose_dates:
        for match in _PROSE_DATE_RE.finditer(masked):
            month = (match.group("m1") or match.group("m2") or "").lower()
            day = match.group("d1") or match.group("d2")
            year = match.group("y1") or match.group("y2")
            try:
                dates.append((date(int(year), _MONTHS[month], int(day)), match.start()))
            except (ValueError, KeyError):
                continue
        # Mask the prose dates too: "April 1, 2026" must not also contribute the
        # bare numbers 1 and 2026 to the numeric pool.
        masked = _PROSE_DATE_RE.sub(lambda m: " " * len(m.group(0)), masked)

    numbers: list[tuple[Decimal, int]] = []
    number_strings: list[tuple[str, int]] = []
    for match in _NUMBER_RE.finditer(masked):
        token = match.group(0)
        number_strings.append((token, match.start()))
        try:
            numbers.append((Decimal(token.replace(",", "")), match.start()))
        except InvalidOperation:  # pragma: no cover — regex guarantees parseable
            continue

    return _ActualIndex(
        view=view,
        tight="".join(tight_chars),
        tight_to_view=tight_to_view,
        numbers=numbers,
        number_strings=number_strings,
        dates=dates,
    )


def _find_label(index: _ActualIndex, label: str) -> list[tuple[int, int]]:
    """Spans (start, end) in view coordinates where `label` occurs.

    Falls back to a whitespace-insensitive search so a CamelCase category value
    like `CustomerEducation` still matches a platform rendering of "Customer
    Education". Nothing else is relaxed — this is not fuzzy matching.

    Word-bounded: a short label like "down" must not match inside an unrelated
    word like "breakdown". Without this, the match is real but meaningless —
    it is scored for proximity to a value as if the platform had actually
    written the word, producing a misleading "too far from its value" failure
    for a label that was never really there.
    """
    needle = _WS.sub(" ", label.strip().lower())
    if not needle:
        return []
    pattern = re.escape(needle)
    if needle[0].isalnum():
        pattern = r"\b" + pattern
    if needle[-1].isalnum():
        pattern = pattern + r"\b"
    spans = [(m.start(), m.end()) for m in re.finditer(pattern, index.view)]
    if spans:
        return spans
    tight_needle = needle.replace(" ", "")
    out: list[tuple[int, int]] = []
    for m in re.finditer(re.escape(tight_needle), index.tight):
        if m.start() >= len(index.tight_to_view) or m.end() > len(index.tight_to_view):
            continue
        out.append(
            (index.tight_to_view[m.start()], index.tight_to_view[m.end() - 1] + 1)
        )
    return out


def _find_direction(index: _ActualIndex, direction: str) -> list[tuple[int, int]]:
    """Spans for a T5 trend direction word, accepting its natural synonyms.

    `direction` is the literal generator token ("up"/"down"/"flat"); the
    platform almost never writes that exact word, so this searches every
    synonym in `_DIRECTION_SYNONYMS` and pools the spans. Unknown words (not
    one of the three) fall back to a literal search, same as any other label.
    """
    words = _DIRECTION_SYNONYMS.get(direction.strip().lower(), (direction,))
    spans: list[tuple[int, int]] = []
    for word in words:
        spans.extend(_find_label(index, word))
    return spans


def _attachment_cost(span: tuple[int, int], value_pos: int) -> tuple[bool, int]:
    """How strongly a label span at `span` claims the value at `value_pos`.

    Returns `(follows, cost)`. Distance is measured from the label's near
    edge, and a label that FOLLOWS its value is charged double. Both choices
    encode how the platform actually writes these answers — "Awareness led
    with 35,726" and "Awareness | 35726" put the label first — so a trailing
    label only wins when no preceding label is in play at all (see
    `_label_owns_a_value`): for a list like "Delivered shipments total
    10,560, Shipped shipments total 4,717, ...", the gap from one item's
    value to the NEXT item's label is only a word or two — doubling that short
    gap can still beat the current item's own (longer) connector phrase on
    raw distance alone, which is what let a later record's label outrank the
    correct one by a couple of characters. `follows` lets the caller refuse to
    let that happen whenever an actual preceding label is anywhere in range.
    """
    start, end = span
    if end <= value_pos:
        return False, value_pos - end
    if start > value_pos:
        return True, (start - value_pos) * 2
    return False, 0  # overlapping: a label containing digits, already excluded upstream


# --- comparison -------------------------------------------------------------


def _consume_number(
    index: _ActualIndex,
    field: ExpectedField,
    used: set[int],
    policy: ComparisonPolicy,
) -> list[int] | None:
    """Positions where this expected number appears unconsumed, or None.

    Multiset semantics: two expected `5`s need two distinct `5`s in the answer,
    so a position is consumed once matched.
    """
    if policy.numeric_form == "string":
        wanted = field.raw.strip().lstrip("$€£¥").strip()
        hits = [
            pos
            for token, pos in index.number_strings
            if token == wanted and pos not in used
        ]
    else:
        hits = [
            pos
            for value, pos in index.numbers
            if value == field.value and pos not in used
        ]
        if not hits:
            hits = _printed_at_lower_precision(index, field, used)
    return hits or None


# "about $79.42 million" for 79421787.31 — a word-scaled rendering is still a
# faithful rounding, just with the trailing zeros spelled out rather than
# printed. Checked immediately after the token in `_printed_at_lower_precision`
# only; it never changes what `_NUMBER_RE` tokenises, so it cannot affect any
# exact-value match elsewhere.
_MAGNITUDE_WORDS: dict[str, int] = {
    "thousand": 3,
    "million": 6,
    "billion": 9,
}
_MAGNITUDE_RE = re.compile(r"\s{0,2}(thousand|million|billion)\b", re.IGNORECASE)


def _printed_at_lower_precision(
    index: _ActualIndex, field: ExpectedField, used: set[int]
) -> list[int]:
    """Positions where the answer prints this number with fewer decimals.

    Observed repeatedly against the live platform, across both domains:

        expected 1339.1438      printed "1339.14"
        expected 2851503384.42  printed "$2,851,503,384"
        expected 50.36          printed "about 50.4%"

    Each is the expected value *rendered shorter*, which HC-3 protects — it
    fails "numeric variance", and dropping cents from 2.8 billion is not
    variance. Scoring them wrong made the platform look worse than it is, which
    is the error that costs us credibility rather than theirs. The third case
    also printed its own numerator and denominator, 4,928 of 9,786, which
    divide to exactly the expected 50.36.

    THE RULE: the printed token must be the expected value correctly rounded to
    whatever precision the platform chose to print — a faithful rendering, not
    merely a nearby number. That is why 4,182,000 is still refused against
    4,182,650.00: it is not a rounding of it at any precision. It is also why
    this is not a tolerance on the value, which the module docstring promises
    there isn't.

    A bare integer therefore counts: "about 22%" is accepted for 22.43, as is
    "-51" for -50.52. That was a deliberate call (2026-10-06) after the
    alternative — a floor of three significant digits — was measured and found
    to change no verdict in the 563 comparisons across the four full CRM and
    Sales runs on disk. It affects only two-digit values, every one of which is
    a percentage in our data, at up to 1.9% error. The trade accepted here is
    that we can no longer distinguish a platform computing a percentage exactly
    from one reporting it to the nearest point.

    The single exception is a value rounded away to nothing: "0.0" for
    0.00001234 is a faithful rounding by the arithmetic, but it carries no
    information about the expected value at all, so a printed zero is refused
    when the expected value is non-zero.
    """

    hits: list[int] = []
    expected = field.value
    if expected is None or expected == 0:
        return hits
    for token, pos in index.number_strings:
        if pos in used:
            continue
        cleaned = token.strip().lstrip("$€£¥").replace(",", "").strip()
        try:
            printed = Decimal(cleaned)
        except (InvalidOperation, ValueError):
            continue
        decimals = -printed.as_tuple().exponent
        if decimals < 0:
            continue
        if printed == 0:
            continue  # every digit rounded away; says nothing about `expected`
        if round(expected, decimals) == printed:
            hits.append(pos)
            continue
        # "$79.42 million" for 79421787.31: the token alone (79.42) is not a
        # faithful rounding of `expected` at its own precision, but it is one
        # once scaled by the magnitude word immediately following it.
        tail = index.view[pos + len(token) : pos + len(token) + 10]
        magnitude_match = _MAGNITUDE_RE.match(tail)
        if magnitude_match is None:
            continue
        extra_digits = _MAGNITUDE_WORDS[magnitude_match.group(1).lower()]
        scale = Decimal(10) ** extra_digits
        scaled = printed * scale
        if scaled == 0:
            continue
        effective_decimals = (
            decimals - extra_digits
        )  # may be negative: tens, hundreds, ...
        if round(expected, effective_decimals) != scaled:
            continue  # not a faithful rendering of the expected value, scaled
        hits.append(pos)
    return hits


def _consume_date(index: _ActualIndex, field: ExpectedField, used: set[int]):
    hits = [
        pos for value, pos in index.dates if value == field.value and pos not in used
    ]
    return hits or None


def _label_owns_a_value(
    label_occurrences: list[tuple[int, str, tuple[int, int]]],
    record_index: int,
    value_positions: list[int],
    limit: int,
) -> tuple[bool, int | None]:
    """Does record `record_index`'s label claim one of its own values?

    For each of the record's values, find which label occurrence — across ALL
    records — claims it most strongly (see :func:`_attachment_cost`). The record
    owns the value if its own label wins. This is what rejects a permuted answer:
    the numbers are all present, but each is claimed by a different record's
    label than the one that declared it.

    Returns (owned, nearest_cost). `nearest_cost` is the best claim distance seen,
    for a message that distinguishes "a different label claims it" from "your
    label is nowhere near any of its values".
    """
    nearest: int | None = None
    for value_pos in value_positions:
        costs = [
            (_attachment_cost(span, value_pos), idx)
            for idx, _raw, span in label_occurrences
        ]
        in_range = [(cost, idx) for cost, idx in costs if cost[1] <= limit]
        # A preceding label in range always outranks a following one, however
        # close the following one measures — see _attachment_cost. Only when
        # nothing precedes the value within range do following labels compete
        # on raw distance, which is the legitimate "N for LABEL" shape.
        preceding_in_range = [(cost, idx) for cost, idx in in_range if not cost[0]]
        pool = preceding_in_range or in_range
        if not pool:
            cost_values = [cost for cost, _ in costs]
            if cost_values:
                best = min(cost_values, key=lambda c: c[1])[1]
                if nearest is None or best < nearest:
                    nearest = best
            continue
        winning_cost, _ = min(pool, key=lambda item: item[0][1])
        if nearest is None or winning_cost[1] < nearest:
            nearest = winning_cost[1]
        if any(cost == winning_cost and idx == record_index for cost, idx in pool):
            return True, nearest
    return False, nearest


def evaluate_answer(
    expected_answer: str,
    actual_answer: str,
    *,
    policy: ComparisonPolicy = DEFAULT_POLICY,
) -> ExactMatchOutcome:
    """Compare a platform answer against the deterministic ground truth.

    NOT_APPLICABLE when `expected_answer` carries nothing deterministic to check
    (a pure-prose T5 wrapper). PASS when every numeric, date and label the
    expected answer declares is present — and every label owns its own value.
    FAIL otherwise, with the first unmet requirements named.
    """
    records = parse_expected(expected_answer)
    index = _build_index(actual_answer, policy)

    off_contract = any(
        f.kind in (FieldKind.MIXED, FieldKind.PROSE) for r in records for f in r
    )

    # A trend record (§ comment on _DIRECTION_SYNONYMS): its last field is a
    # LABEL naming up/down/flat and it has at least one NUMERIC sibling. The
    # record_index -> direction-word map drives two scoped relaxations below.
    trend_direction: dict[int, str] = {}
    for record_index, record in enumerate(records):
        if not record or record[-1].kind is not FieldKind.LABEL:
            continue
        candidate = record[-1].raw.strip().lower()
        if candidate in _DIRECTION_SYNONYMS and any(
            f.kind is FieldKind.NUMERIC for f in record
        ):
            trend_direction[record_index] = candidate

    checks = 0
    used_numeric: set[int] = set()
    used_date: set[int] = set()
    failures: list[str] = []
    satisfied: list[str] = []
    unsatisfied: list[str] = []

    # Every label the expected answer declares, wherever it occurs in the answer.
    # Ownership is decided against this whole set: a value claimed by a DIFFERENT
    # record's label is the permuted-answer case, and must fail even though the
    # multiset of numbers is right.
    label_occurrences: list[tuple[int, str, tuple[int, int]]] = []
    for record_index, record in enumerate(records):
        for field in record:
            if field.kind is FieldKind.LABEL:
                is_direction_field = (
                    record_index in trend_direction and field is record[-1]
                )
                spans = (
                    _find_direction(index, field.raw)
                    if is_direction_field
                    else _find_label(index, field.raw)
                )
                for span in spans:
                    label_occurrences.append((record_index, field.raw, span))

    # Pass 1 — values.
    record_value_positions: list[list[int]] = []
    for record_index, record in enumerate(records):
        positions: list[int] = []
        for field in record:
            if field.kind is FieldKind.NUMERIC:
                checks += 1
                key = f"value:{field.value}"
                hits = _consume_number(index, field, used_numeric, policy)
                if (
                    hits is None
                    and record_index in trend_direction
                    and field.value is not None
                    and field.value < 0
                ):
                    # Trend record: the platform says "a decrease of $X", never
                    # "-$X" — the sign is the verb, not a digit. Direction
                    # itself is still checked separately below.
                    magnitude = ExpectedField(
                        FieldKind.NUMERIC, field.raw, value=-field.value
                    )
                    hits = _consume_number(index, magnitude, used_numeric, policy)
                if hits is None:
                    failures.append(f"value {field.raw!r} not present")
                    unsatisfied.append(key)
                    continue
                used_numeric.add(hits[0])
                satisfied.append(key)
                positions.extend(hits)
            elif field.kind is FieldKind.DATE:
                checks += 1
                key = f"date:{field.value}"
                hits = _consume_date(index, field, used_date)
                if hits is None:
                    failures.append(f"date {field.raw!r} not present")
                    unsatisfied.append(key)
                    continue
                used_date.add(hits[0])
                satisfied.append(key)
                positions.extend(hits)
            elif field.kind is FieldKind.MIXED:
                # Off-contract pair (§9.3): hold it to its numbers, not its prose.
                for inner in field.inner_numerics:
                    checks += 1
                    synthetic = ExpectedField(
                        FieldKind.NUMERIC, str(inner), value=inner
                    )
                    key = f"value:{inner}"
                    hits = _consume_number(index, synthetic, used_numeric, policy)
                    if hits is None:
                        failures.append(f"value {inner} not present")
                        unsatisfied.append(key)
                        continue
                    used_numeric.add(hits[0])
                    satisfied.append(key)
                    positions.extend(hits)
        record_value_positions.append(positions)

    # Pass 2 — labels, and whether each owns its own value.
    if policy.require_labels:
        for record_index, record in enumerate(records):
            value_positions = record_value_positions[record_index]
            for field in record:
                if field.kind is not FieldKind.LABEL:
                    continue
                checks += 1
                key = f"label:{field.raw}"
                own_spans = [
                    span
                    for idx, raw, span in label_occurrences
                    if idx == record_index and raw == field.raw
                ]
                if not own_spans:
                    failures.append(f"label {field.raw!r} not present")
                    unsatisfied.append(key)
                    continue
                if not value_positions:
                    satisfied.append(key)
                    continue  # label-only record: presence is the requirement

                owned, nearest = _label_owns_a_value(
                    label_occurrences,
                    record_index,
                    value_positions,
                    policy.label_proximity_chars,
                )
                if owned:
                    satisfied.append(key)
                    continue
                unsatisfied.append(key)
                if nearest is not None and nearest <= policy.label_proximity_chars:
                    failures.append(
                        f"label {field.raw!r} present but a different label claims "
                        "its value"
                    )
                else:
                    failures.append(
                        f"label {field.raw!r} present but {nearest} chars from any "
                        f"of its values (limit {policy.label_proximity_chars})"
                    )

    if checks == 0:
        return ExactMatchOutcome(
            ExactMatchResult.NOT_APPLICABLE,
            "expected_answer carries no deterministic value to compare",
            off_contract=off_contract,
        )
    keys = {
        "satisfied": tuple(sorted(satisfied)),
        "unsatisfied": tuple(sorted(unsatisfied)),
    }
    if failures:
        detail = "; ".join(failures[:4])
        if len(failures) > 4:
            detail += f" (+{len(failures) - 4} more)"
        return ExactMatchOutcome(
            ExactMatchResult.FAIL, detail, off_contract=off_contract, **keys
        )
    return ExactMatchOutcome(
        ExactMatchResult.PASS,
        f"{checks} requirement(s) satisfied",
        off_contract=off_contract,
        **keys,
    )


def exact_match(
    expected_answer: str,
    actual_answer: str,
    *,
    policy: ComparisonPolicy = DEFAULT_POLICY,
) -> ExactMatchResult:
    """Thin wrapper for call sites that only want the verdict."""
    return evaluate_answer(expected_answer, actual_answer, policy=policy).result


def extract_numerics(text: str) -> list[str]:
    """Every numeric literal in `text`, dates excluded, order preserved.

    Kept for the rephrase-group agreement check (§9.5) and for diagnostics.
    """
    return _NUMBER_RE.findall(_strip_dates(text or ""))
