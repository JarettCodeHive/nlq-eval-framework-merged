"""Deterministic answer comparison — §HC-3 zero numeric tolerance.

Reported in the scorecard row per §11.2 as `exact_match_result`, alongside the
judge scores. Per §11.3 the two are always shown side by side, NEVER combined
into a composite — they measure different things.

WHAT IS COMPARED
----------------
`expected_answer` is machine-generated by executing `reference_sql` (§9.3), and
the generator emits a structured shape:

    28731                                          bare scalar
    26677920.26                                    bare scalar, decimal
    Standard | 6229                                one labelled value
    Awareness | 35726; Retention | 34685           ordered labelled list

`;` separates records, `|` separates fields inside a record. That structure is
what makes an exact comparison possible: every field is classified and checked
on its own terms rather than the whole string being pattern-matched.

    NUMERIC   the field is wholly a number         -> must be present BY VALUE
    DATE      the field is wholly an ISO date      -> must be present, exact day
    LABEL     short entity/category, no digits     -> must be present, and must
                                                      sit next to its own value
    MIXED     digits inside prose (off-contract)   -> numerics required, words not
    PROSE     no digits, not label-shaped          -> advisory only

The LABEL rule is the load-bearing one. Comparing numerics alone passes an
answer that attaches every right number to the wrong entity — "Bob Smith closed
4,182,650.00" against an expected "Priya Raghavan — 4,182,650.00" — which is the
exact shape of most T4/T5 pairs and of the Appendix A worked example. A label is
therefore required to appear WITHIN `label_proximity_chars` of its own value, so
a permuted answer fails even though its multiset of numbers is right.

DECISIONS TAKEN AHEAD OF THE OPEN ITEMS
---------------------------------------
OI-2 (what "identical" compares) is not yet ruled on by the Platform Owner, and
OI-3 (date tolerance) likewise. Rather than leave the scorer unusable until they
land, both are settled here as an explicit, reversible policy:

* **Numerics compare by VALUE, not by string** (`numeric_form="value"`). §HC-3
  protects "answer phrasing, response length and dashboard styling" and fails
  only "numeric variance"; a thousands separator, a currency prefix and a
  trailing `.00` change the rendering, not the value. `28,731` therefore equals
  `28731`, and `4,182,000` still fails `4,182,650.00` because that is a real
  loss of value. Byte-identical comparison remains available as
  `numeric_form="string"` — one flag, if the client rules the other way.
* **Dates compare by day, with zero tolerance** (C10: the ±1 day tolerance from
  earlier drafts is "not carried forward"). ISO on the expected side; ISO or a
  month-name rendering on the actual side, because the platform writes dates in
  prose and a month name cannot be confused with anything else.

Deliberately NOT done: spelled-out numerals ("Five" for `5`) are not recognised.
The judge scores them 5 and should — but teaching the *scorer* number words means
expected `1` matches any answer containing the word "one", which trades a rare
false fail for a common false pass. The divergence between the two scores on such
an answer is intentional and visible side by side (§11.3).

RESIDUAL RISK, STATED PLAINLY
-----------------------------
For a bare scalar with no label to anchor it, presence is still presence: a long
answer carrying a category breakdown can contain the expected number incidentally
and pass. Nothing in the response payload lets us bind a bare number to its role,
so this is a floor on the method, not a bug to fix here. Labelled pairs — the
majority of T4/T5 — are not exposed to it.
"""

